import fs from 'node:fs';
import path from 'node:path';

const manifest = JSON.parse(fs.readFileSync('_work/topic-manifest.json', 'utf8'));
const TIGHT = path.resolve('_work/tight');

function countFiles(topic) {
  const dir = path.join(TIGHT, topic);
  if (!fs.existsSync(dir)) return 0;
  return fs.readdirSync(dir).filter((f) => f.endsWith('.md')).length;
}

function countQuestions(filePath) {
  if (!fs.existsSync(filePath)) return 0;
  const text = fs.readFileSync(filePath, 'utf8');
  const idx = text.indexOf('## Questions Covered');
  if (idx < 0) return 0;
  const nextH2 = text.indexOf('\n## ', idx + 22);
  const block = nextH2 > 0 ? text.slice(idx, nextH2) : text.slice(idx, idx + 8000);
  return (block.match(/^\d+\.\s/gm) || []).length;
}

const topics = fs.readdirSync(TIGHT, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

let totalFiles = 0;
let totalQuestions = 0;
for (const t of topics) {
  const files = fs.readdirSync(path.join(TIGHT, t)).filter((f) => f.endsWith('.md'));
  totalFiles += files.length;
  for (const f of files) {
    totalQuestions += countQuestions(path.join(TIGHT, t, f));
  }
}

let md = `# Interview Prep — Study Guide

> **Start here.** All study notes live under \`_work/tight/\`. Clean (full) versions: \`_work/clean/\`.

**Library stats:** ${topics.length} topics · ${totalFiles} files · ~${totalQuestions} questions

---

## How to use these notes

1. **Pick a learning path** below based on your target role.
2. Study **tight** files first — condensed prose with full code examples.
3. Drill **Questions Covered** at the top of each file, then try answering without looking.
4. Follow **Related Topics** at the bottom of each file to chain concepts.
5. Use **clean** versions when you need fuller explanations.

---

## Learning paths

`;

for (const p of manifest.paths) {
  md += `### ${p.title}\n\n`;
  md += `| Step | Topic | Files to study |\n|------|-------|----------------|\n`;
  let step = 1;
  for (const block of p.order) {
    const fileList = block.files.map((f) => f.replace(/\.md$/i, '')).join(', ');
    md += `| ${step++} | **${block.topic}** | ${fileList} |\n`;
  }
  md += '\n';
}

md += `---

## All topics

| Topic | Files | Folder |
|-------|------:|--------|
`;

for (const t of topics) {
  const n = countFiles(t);
  md += `| ${t} | ${n} | \`_work/tight/${t}/\` |\n`;
}

md += `
---

## Recommended pairings

| If you're studying… | Also review… |
|---------------------|--------------|
| **Angular** | TypeScript, RxJS, NgRx, React (for comparison) |
| **React** | JavaScript, TypeScript, Redux Toolkit, Next.js |
| **C# / .NET** | SQL Server, Web API, Entity Framework, Azure |
| **Docker** | Kubernetes, Azure DevOps, Microservices |
| **Microservices** | System Design, Docker, Kubernetes, Message queues |
| **JavaScript** | TypeScript → then React or Angular |

---

## Recently added / improved

- **TypeScript** — new 4-file topic (Basics → Advanced)
- **Angular Modern Features** — Signals, standalone, \`inject()\`, \`@if/@for\`, zoneless
- **React** — 16-file library (Basics through Redux/Zustand/Next.js/Native)
- **Related Topics** footers — cross-links at the bottom of key files
- **Interview Comparisons** — side-by-side framework and architecture decisions

---

## Topic quick links

`;

const anchors = {
  'C#': 'Backend & .NET',
  'Sql Server': 'Backend & .NET',
  'TypeScript': 'Languages',
  'Javascript': 'Languages',
  'Angular': 'Frontend',
  'React': 'Frontend',
  'Docker': 'DevOps',
  'Kubernetes': 'DevOps',
  'Azure Cloud': 'Cloud',
  'Azure DevOps': 'Cloud',
  'Microservices': 'Architecture',
  'System Design': 'Architecture',
  'Data Structures and Algorithms': 'CS Fundamentals',
  'Important Concepts': 'Cross-cutting',
};

const groups = {};
for (const t of topics) {
  const g = anchors[t] ?? 'Other';
  if (!groups[g]) groups[g] = [];
  groups[g].push(t);
}

for (const [group, list] of Object.entries(groups)) {
  md += `**${group}:** ${list.map((t) => `\`${t}\``).join(' · ')}\n\n`;
}

md += `---

*Generated by \`_work/build-study-guide.mjs\`. Re-run after adding topics.*
`;

fs.writeFileSync('_work/STUDY.md', md, 'utf8');
console.log(`Wrote _work/STUDY.md (${md.length} chars, ${totalFiles} files, ~${totalQuestions} questions)`);
